import { createUIMessageStreamResponse, type UIMessage, type UIMessageChunk } from "ai";
import { start } from "workflow/api";
import { chatTurn } from "@/workflows/chat-turn";
import { DEFAULT_MODEL } from "@/lib/ai/provider";
import { extractPromptText, type ChatTurnInput } from "@/lib/ai/chat-turn";
import {
  isSuperContinueMessage,
  lastRealUserMessage,
} from "@/lib/ai/messages/continuation";
import { sealTurnSecret } from "@/lib/ai/turn-secret";
import { getSession, SESSION_COOKIE } from "@/lib/auth/session";
import { checkRateLimit, clientIp } from "@/lib/auth/rate-limit";
import {
  ensureConversation,
  saveUIMessage,
  setConversationRun,
} from "@/lib/db/conversations";
import { TITLE_MAX_CHARS } from "@/lib/ai/title";

export const maxDuration = 300;

type ChatBody = {
  messages: UIMessage[];
  model?: string;
  conversationId?: string;
  title?: string | null;
  walletAddress?: string;
  walletChain?: string;
  superUnlocked?: boolean;
  /** Set by the client when it resumes a turn after the unlock lands. */
  superJustUnlocked?: boolean;
  /** The transport's request kind; regenerating reuses the old message id. */
  trigger?: "submit-message" | "regenerate-message";
  messageId?: string;
};

/**
 * Starts a durable chat turn and hands its stream to the browser.
 *
 * The turn used to be generated by this response, which meant a reload or a
 * closed tab cancelled the model mid-answer. It now runs in a workflow: the
 * route records which run owns the chat and returns a reader on the run's
 * stream, and `GET /api/chat/[id]/stream` replays that stream from the last
 * chunk a reconnecting client saw. Authorization, the conversation, and the
 * user message are still resolved here, before anything is signed or stored.
 */
export async function POST(req: Request) {
  const {
    messages,
    model,
    conversationId,
    title,
    walletAddress,
    walletChain,
    superUnlocked,
    superJustUnlocked,
    trigger,
    messageId,
  }: ChatBody = await req.json();

  // Borrowed for this turn only. It is sealed before it crosses into the
  // workflow so the run's event log holds ciphertext, never the token; the
  // refresh token that mints it stays in the browser.
  const intentsAccessToken =
    req.headers.get("x-intents-access-token")?.trim() || undefined;

  if (!process.env.NEAR_AI_CLOUD_API_KEY) {
    return Response.json(
      {
        error:
          "The assistant is not configured. Please check environment keys and try again.",
      },
      { status: 503 },
    );
  }

  if (!process.env.TOOL_APPROVAL_SECRET) {
    return Response.json(
      {
        error:
          "Approvals are not configured. Please check necessary permissions and try again.",
      },
      { status: 503 },
    );
  }

  const { limited: chatLimited } = checkRateLimit(`chat:${clientIp(req)}`, 30, 60_000);
  if (chatLimited) {
    return Response.json({ error: "An error occurred." }, { status: 429 });
  }

  // Logged-out visitors keep the stream-only behavior so the demo never
  // blocks on login. Logged-in users get persistence below.
  const cookieId = req.headers
    .get("cookie")
    ?.split(";")
    .map((c) => c.trim())
    .find((c) => c.startsWith(`${SESSION_COOKIE}=`))
    ?.slice(SESSION_COOKIE.length + 1);
  const session = cookieId
    ? await getSession(decodeURIComponent(cookieId))
    : null;

  if (conversationId && !session) {
    return Response.json({ error: "Not signed in." }, { status: 401 });
  }

  let conv: { id: string; slug: string } | null = null;
  // A new chat is named by the workflow, so switching chats or closing the
  // tab mid-stream cannot orphan it as untitled.
  const isNewChat = !conversationId;
  let newChatPrompt = "";
  if (session) {
    try {
      // Untitled stays NULL and the interface shows "New chat" as a
      // fallback. A stored "New chat" string always means the user typed
      // exactly that, so generation never overwrites it.
      const firstTitle = title?.trim().slice(0, TITLE_MAX_CHARS) || null;
      conv = await ensureConversation({
        userId: session.userId,
        conversationId,
        title: firstTitle,
      });
      const lastUser = [...messages].reverse().find((m) => m.role === "user");
      const lastTypedUser = lastRealUserMessage(messages);
      if (isNewChat) newChatPrompt = extractPromptText(lastTypedUser).slice(0, 500);
      // The unlock continuation is a transport instruction. It is not a real
      // user message, so it must never become a bubble in saved history.
      if (lastUser && !isSuperContinueMessage(lastUser)) {
        try {
          await saveUIMessage(conv.id, lastUser);
        } catch {
          // Save failure never blocks the stream. The next turn retries.
        }
      }
    } catch {
      conv = null;
    }
  }

  const activeAddress = session?.address || walletAddress || null;
  const activeChain = session?.chain || walletChain || null;
  const accountKind = session?.accountKind ?? "wallet";

  // The token is the real signal: a live access token means the account is
  // unlocked for this turn, even if the client's cached flag is stale.
  const superUnlockedNow = Boolean(intentsAccessToken) || superUnlocked === true;

  // The flag only shapes prose, and only when a live token really is here;
  // the token remains the gate for the read itself.
  const justUnlocked = Boolean(intentsAccessToken) && superJustUnlocked === true;

  const input: ChatTurnInput = {
    messages,
    model: model ?? DEFAULT_MODEL,
    conversationId: conv?.id ?? null,
    userId: session?.userId ?? null,
    accountKind,
    intentsAccountId: session?.intentsAccountId ?? null,
    accountId:
      session?.accountKind === "passkey" ? (session.address ?? null) : null,
    activeAddress,
    activeChain,
    superUnlocked: superUnlockedNow,
    superJustUnlocked: justUnlocked,
    titlePrompt: newChatPrompt,
    nameNewChat: isNewChat,
    regeneratedMessageId:
      trigger === "regenerate-message" ? messageId : undefined,
    intentsSecret: intentsAccessToken ? sealTurnSecret(intentsAccessToken) : null,
  };

  let run;
  try {
    run = await start(chatTurn, [input]);
  } catch (error) {
    console.error(
      "[chat] run failed to start",
      error instanceof Error ? error.message.slice(0, 200) : "unknown",
    );
    return Response.json({ error: "An error occurred." }, { status: 500 });
  }

  // Recorded before the response so a reload in the next moment knows which
  // run to reconnect to. A failure here costs resume, not the turn, so the
  // stream still goes out.
  if (conv && session) {
    try {
      await setConversationRun(session.userId, conv.id, run.runId);
    } catch {
      // The run still generates and persists; it just cannot be resumed.
    }
  }

  const headers = new Headers();
  headers.set("x-workflow-run-id", run.runId);
  if (conv) {
    headers.set("x-conversation-id", conv.id);
    headers.set("x-conversation-slug", conv.slug);
  }

  return createUIMessageStreamResponse({
    stream: run.readable as ReadableStream<UIMessageChunk>,
    headers,
  });
}
