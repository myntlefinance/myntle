import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/* Build the list of local brand marks the app can serve.
 *
 * The curated network and token logos are inlined in uploadedSvgs.ts so the
 * first screen paints without a request. Everything else in public/networks
 * and public/tokens is served as a static file. This manifest is what lets
 * NetworkIcon and TokenAvatar find those files without a 404 per unknown
 * chain. Run `bun run icons` after adding or removing an SVG.
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "components/finance/iconFiles.ts");

function svgNames(dir) {
  return readdirSync(join(root, "public", dir))
    .filter((name) => name.endsWith(".svg"))
    .map((name) => name.slice(0, -4))
    .sort();
}

function list(names) {
  return names.map((name) => `  "${name}",`).join("\n");
}

const networks = svgNames("networks");
const tokens = svgNames("tokens");

const source = `// Generated by scripts/build-icon-manifest.mjs. Do not edit by hand.
// Run \`bun run icons\` after adding or removing an SVG in public/networks
// or public/tokens.

export const NETWORK_FILES = [
${list(networks)}
] as const;

export const TOKEN_FILES = [
${list(tokens)}
] as const;
`;

writeFileSync(out, source);
console.log(
  `Wrote ${networks.length} network and ${tokens.length} token files to ${out}`,
);
